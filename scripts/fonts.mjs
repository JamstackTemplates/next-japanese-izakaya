// Regenerates app/fonts.css from the installed Fontsource packages, keeping only the WOFF2 files.
// Fontsource's own CSS also lists a WOFF fallback for every subset; no current browser needs it, and
// for Japanese fonts (about 120 subsets per weight) it would double the size of the build for nothing.
// Usage: npm run fonts   (after changing a font or weight in FONTS below)
import { readFileSync, writeFileSync } from 'node:fs';

/** [package, CSS file] pairs. Each CSS file is one weight; load only the weights the site uses. */
const FONTS = [
  ['@fontsource/zen-kaku-gothic-new', '400.css'],
  ['@fontsource/zen-kaku-gothic-new', '700.css'],
  ['@fontsource/shippori-mincho', '700.css'],
  ['@fontsource/yuji-syuku', '400.css'],
];

const root = new URL('../', import.meta.url);
const parts = FONTS.map(([pkg, file]) => {
  const css = readFileSync(new URL(`node_modules/${pkg}/${file}`, root), 'utf8');
  const rewritten = css
    .replace(/,\s*url\([^)]+\.woff\) format\('woff'\)/g, '')
    .replace(/url\(\.\/files\//g, `url(../node_modules/${pkg}/files/`);
  if (/\.woff\)/.test(rewritten)) throw new Error(`${pkg}/${file}: unexpected WOFF reference left`);
  return `/* ${pkg}/${file} */\n${rewritten.trim()}\n`;
});

writeFileSync(new URL('app/fonts.css', root),
  `/* Generated by scripts/fonts.mjs from the Fontsource packages (SIL Open Font License 1.1). Do not edit by hand. */\n${parts.join('\n')}`);
console.log(`Wrote app/fonts.css (${FONTS.length} font files).`);
